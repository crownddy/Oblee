import type { Metadata } from "next";
import type { MetadataRoute } from "next";
import type { EventDetail } from "@/lib/types/domain";
import { categoryLabel } from "@/lib/constants";
import { formatEventDate } from "@/lib/utils/format";

export const SITE_NAME = "Oblee";
export const DEFAULT_TITLE = "Oblee — find the party you love";
export const DEFAULT_DESCRIPTION =
  "Oblee is an African event and party discovery platform. Discover events, save your favourites and find places to enjoy.";

/** Public, canonical, indexable pages that never change per request. */
export const STATIC_PAGES = ["/", "/explore", "/privacy", "/terms"] as const;

/** Generated by `app/opengraph-image.tsx`. */
export const OPEN_GRAPH_IMAGE = "/opengraph-image";

/**
 * Query parameters that identify a discovery view. Everything else (`utm_*`,
 * `fbclid`, `gclid`, …) is dropped from canonicals so a shared tracking link
 * never indexes as a separate page.
 */
const DISCOVERY_PARAMS = ["q", "cat", "date", "page"] as const;

/** Google caps a sitemap at 50k URLs; this keeps one file comfortably small. */
export const MAX_SITEMAP_EVENTS = 5000;

const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isEventId(value: string | undefined | null): boolean {
  return typeof value === "string" && UUID_PATTERN.test(value);
}

function first(value: string | string[] | undefined): string {
  return Array.isArray(value) ? (value[0] ?? "") : (value ?? "");
}

/**
 * Canonical path for a route: recognised discovery parameters survive in a
 * stable order, tracking noise is removed, and the home page stays bare.
 */
export function canonicalPath(
  path: string,
  search: Record<string, string | string[] | undefined> = {},
): string {
  const base = path.split("?")[0] ?? "";
  const clean = base.replace(/\/+$/, "") || "/";
  const params = new URLSearchParams();
  for (const key of DISCOVERY_PARAMS) {
    const value = first(search[key]).trim();
    if (!value) continue;
    // Page 1 is the same document as the bare route.
    if (key === "page" && (value === "1" || !/^\d+$/.test(value))) continue;
    params.set(key, value);
  }
  const query = params.toString();
  return query ? `${clean}?${query}` : clean;
}

/** True when the URL describes a filtered or paginated view rather than the base page. */
export function isFilteredView(search: Record<string, string | string[] | undefined> = {}): boolean {
  return Boolean(first(search.q).trim() || first(search.date).trim() || first(search.cat).trim());
}

/**
 * The home page and `/explore` render the same discovery list, so filtered home
 * URLs stay out of the index while filtered explore URLs keep their own
 * canonical (filters are a real part of the product, not duplicates).
 */
export function discoveryRobots(
  mode: "home" | "explore",
  search: Record<string, string | string[] | undefined> = {},
): Metadata["robots"] {
  if (mode === "home" && isFilteredView(search)) return { index: false, follow: true };
  return { index: true, follow: true };
}

export function absoluteUrl(siteUrl: string, path: string): string {
  return `${siteUrl.replace(/\/+$/, "")}${path.startsWith("/") ? path : `/${path}`}`;
}

/** Public, published events are the only ones search engines may index. */
export function isIndexableEvent(event: Pick<EventDetail, "status" | "visibility">): boolean {
  return event.status === "published" && event.visibility === "public";
}

/**
 * Meta description built only from stored event fields. Empty descriptions fall
 * back to the category and place the page already shows, never to filler copy.
 */
export function eventDescription(event: EventDetail): string {
  const stored = event.description.trim();
  if (stored) return stored.slice(0, 160);
  const place = event.city ? `${event.venue}, ${event.city}` : event.venue;
  return `${event.title} — ${categoryLabel(event.category)} at ${place} on ${formatEventDate(
    event.startsAt,
    event.timezone,
  )}. Discover it on Oblee.`;
}

export function eventMetadata(event: EventDetail): Metadata {
  const indexable = isIndexableEvent(event);
  const description = eventDescription(event);
  return {
    title: event.title,
    description,
    alternates: indexable ? { canonical: `/events/${event.id}` } : undefined,
    // Archived events stay reachable for their organiser and for admins, and
    // private events stay reachable for people holding a grant; neither belongs
    // in an index.
    robots: indexable ? { index: true, follow: true } : { index: false, follow: false },
    openGraph: {
      type: "article",
      title: event.title,
      description,
      siteName: SITE_NAME,
      url: `/events/${event.id}`,
      // The shared brand card: event covers sit in a private bucket behind
      // signed URLs that expire, so they cannot be handed to crawlers.
      images: [{ url: OPEN_GRAPH_IMAGE, width: 1200, height: 630, alt: DEFAULT_TITLE }],
    },
    twitter: { card: "summary_large_image", title: event.title, description },
  };
}

export function websiteJsonLd(siteUrl: string): Record<string, unknown> {
  return {
    "@context": "https://schema.org",
    "@type": "WebSite",
    name: SITE_NAME,
    url: absoluteUrl(siteUrl, "/"),
    description: DEFAULT_DESCRIPTION,
    inLanguage: "en",
  };
}

/**
 * Only the facts the product actually publishes: a name, the site and the mark.
 * No address, phone number or founding date is stored anywhere, so none is sent.
 */
export function organisationJsonLd(siteUrl: string): Record<string, unknown> {
  return {
    "@context": "https://schema.org",
    "@type": "Organization",
    name: SITE_NAME,
    url: absoluteUrl(siteUrl, "/"),
    logo: absoluteUrl(siteUrl, "/brand/mark.png"),
    description: DEFAULT_DESCRIPTION,
  };
}

/**
 * Event structured data for public published events. Every value comes from the
 * event row; fields the row does not hold (end date, performers, images served
 * from the private bucket) are omitted rather than guessed.
 */
export function eventJsonLd(
  event: EventDetail,
  siteUrl: string,
): Record<string, unknown> | null {
  if (!isIndexableEvent(event)) return null;

  const url = absoluteUrl(siteUrl, `/events/${event.id}`);
  const place: Record<string, unknown> = {
    "@type": "Place",
    name: event.venue,
    address: {
      "@type": "PostalAddress",
      ...(event.city ? { addressLocality: event.city } : {}),
    },
  };

  const data: Record<string, unknown> = {
    "@context": "https://schema.org",
    "@type": "Event",
    name: event.title,
    startDate: event.startsAt,
    eventStatus: "https://schema.org/EventScheduled",
    eventAttendanceMode: "https://schema.org/OfflineEventAttendanceMode",
    location: place,
    url,
    isAccessibleForFree: event.isFree,
  };

  if (event.description.trim()) data.description = event.description.trim().slice(0, 500);
  if (event.organiserName) {
    data.organizer = { "@type": "Organization", name: event.organiserName };
  }

  // Prices come from the ticket tiers the page already lists; free events show a
  // Free badge, paid events with no tiers show no price at all.
  const price = event.isFree ? 0 : event.priceFrom;
  if (price !== null && price !== undefined) {
    data.offers = {
      "@type": "Offer",
      price,
      priceCurrency: "NGN",
      availability: "https://schema.org/InStock",
      url,
    };
  }

  return data;
}

/** JSON for a `<script type="application/ld+json">` block, safe against `</script>` breaks. */
export function serializeJsonLd(value: unknown): string {
  return JSON.stringify(value).replace(/</g, "\\u003c").replace(/>/g, "\\u003e");
}

export interface SitemapEvent {
  id: string;
  updatedAt: string | null;
}

function validDate(value: string | null): Date | undefined {
  if (!value) return undefined;
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? undefined : date;
}

/**
 * Sitemap entries: the fixed public pages plus one URL per public published
 * event. Duplicates collapse, invalid ids are skipped, and a missing timestamp
 * omits `<lastmod>` instead of inventing a date.
 */
export function buildSitemapEntries(
  siteUrl: string,
  events: SitemapEvent[] = [],
  staticPages: readonly string[] = STATIC_PAGES,
): MetadataRoute.Sitemap {
  const seen = new Set<string>();
  const entries: MetadataRoute.Sitemap = [];

  for (const path of staticPages) {
    const url = absoluteUrl(siteUrl, path);
    if (seen.has(url)) continue;
    seen.add(url);
    entries.push({ url, changeFrequency: path === "/explore" ? "daily" : "weekly", priority: path === "/" ? 1 : 0.7 });
  }

  let count = 0;
  for (const event of events) {
    if (count >= MAX_SITEMAP_EVENTS) break;
    if (!isEventId(event.id)) continue;
    const url = absoluteUrl(siteUrl, `/events/${event.id}`);
    if (seen.has(url)) continue;
    seen.add(url);
    const lastModified = validDate(event.updatedAt);
    entries.push({
      url,
      ...(lastModified ? { lastModified } : {}),
      changeFrequency: "weekly",
      priority: 0.8,
    });
    count += 1;
  }

  return entries;
}

/** Google Search Console HTML-tag verification, only when the operator supplies a token. */
export function searchConsoleVerification(
  token: string | undefined = process.env.GOOGLE_SITE_VERIFICATION,
): Metadata["verification"] {
  const value = token?.trim();
  return value ? { google: value } : undefined;
}

